"""Intraday execution engine (v2.7.8).

Replays minute-bar data in chronological order against a swing plan.
Records the first trigger time and price.  Does NOT use future data.

This module does NOT connect to brokers, does NOT place real orders, and
does NOT constitute investment advice.
"""

from __future__ import annotations

from typing import Any

import pandas as pd

from quantdesk.paper.market_rules import (
    board_type_for_symbol,
    is_valid_order_quantity,
    lot_size_for_symbol,
)
from quantdesk.utils import safe_float, safe_int

DISCLAIMER = "仅用于策略学习与模拟验证，不构成投资建议。"


def _in_zone(price: float, zone: dict[str, Any]) -> bool:
    low = safe_float(zone.get("price_low"), 0.0) or 0.0
    high = safe_float(zone.get("price_high"), float("inf")) or float("inf")
    return low <= price <= high


def simulate_intraday_plan(
    plan: dict[str, Any],
    intraday_df: pd.DataFrame | None,
    *,
    holding: bool = False,
) -> dict[str, Any]:
    """Simulate a swing plan against intraday minute bars.

    Parameters
    ----------
    plan : dict
        The swing plan generated by ``build_swing_plan``.
    intraday_df : DataFrame or None
        Minute-bar data with columns: datetime, open, high, low, close, volume.
        If None or empty, returns is_reliable=False.
    holding : bool
        Whether the symbol is currently held (affects sell-zone checking).

    Returns
    -------
    dict with triggered, action, trigger_type, trigger_time, trigger_price, etc.
    """

    symbol = plan.get("symbol", "")
    trade_date = plan.get("trade_date") or plan.get("valid_for_date") or ""
    base = {
        "symbol": symbol,
        "trade_date": trade_date,
        "plan_date": plan.get("plan_date", ""),
        "disclaimer": DISCLAIMER,
    }

    if intraday_df is None or (isinstance(intraday_df, pd.DataFrame) and intraday_df.empty):
        return {
            **base,
            "triggered": False,
            "action": "none",
            "is_reliable": False,
            "reason": "缺少盘中数据，无法判断计划价格是否真实出现。",
        }

    df = intraday_df.copy()
    if "datetime" in df.columns:
        df = df.sort_values("datetime").reset_index(drop=True)
    elif "time" in df.columns:
        df = df.sort_values("time").reset_index(drop=True)

    buy_zones = plan.get("buy_zones") or []
    sell_zones = plan.get("sell_zones") or []
    no_chase = safe_float(plan.get("no_chase_above"), float("inf")) or float("inf")
    quantity = safe_int(plan.get("quantity"), 0) or 0
    board_lot = lot_size_for_symbol(symbol, name=str(plan.get("name") or ""))
    board_type = board_type_for_symbol(symbol, name=str(plan.get("name") or ""))
    if not is_valid_order_quantity(
        quantity,
        lot_size=board_lot,
        board_type=board_type,
    ):
        return {
            **base,
            "triggered": False,
            "action": "none",
            "quantity": 0,
            "is_reliable": False,
            "reason": f"计划数量缺失或不足该板块最小整手（{board_lot} 股），未模拟盘中成交。",
        }

    # Replay in chronological order
    for _, row in df.iterrows():
        bar_high = safe_float(row.get("high"))
        bar_low = safe_float(row.get("low"))
        bar_close = safe_float(row.get("close"))
        bar_time = str(row.get("datetime") or row.get("time") or "")

        if bar_high is None or bar_low is None:
            continue

        # Check sell zones first (if holding)
        if holding:
            for zone in sell_zones:
                # Stop loss: price drops into zone
                if zone["type"] == "stop_loss" and bar_low <= safe_float(zone.get("price_high"), float("inf")):
                    trigger_price = safe_float(zone.get("price_high"), bar_low)
                    return {
                        **base,
                        "triggered": True,
                        "action": "sell",
                        "trigger_type": zone["type"],
                        "trigger_time": bar_time,
                        "trigger_price": round(trigger_price, 4),
                        "quantity": quantity,
                        "reason": zone.get("reason", "止损触发"),
                        "confidence": "high",
                        "intraday_source": "1m",
                        "is_reliable": True,
                    }
                # Take profit: price rises into zone
                if zone["type"] == "take_profit" and bar_high >= safe_float(zone.get("price_low"), float("inf")):
                    trigger_price = safe_float(zone.get("price_low"), bar_high)
                    return {
                        **base,
                        "triggered": True,
                        "action": "sell",
                        "trigger_type": zone["type"],
                        "trigger_time": bar_time,
                        "trigger_price": round(trigger_price, 4),
                        "quantity": quantity,
                        "reason": zone.get("reason", "止盈触发"),
                        "confidence": "medium",
                        "intraday_source": "1m",
                        "is_reliable": True,
                    }

        # Check buy zones (if not holding)
        if not holding:
            for zone in buy_zones:
                # No-chase only applies to breakout
                if zone["type"] == "breakout_buy" and bar_close is not None and bar_close > no_chase:
                    continue

                if zone["type"] == "pullback_buy" and bar_low <= safe_float(zone.get("price_high"), float("inf")):
                    # Bar dipped into or through the pullback zone
                    zone_low = safe_float(zone.get("price_low"), 0)
                    zone_high = safe_float(zone.get("price_high"), float("inf"))
                    if bar_low <= zone_high:
                        trigger_price = round(min(max(bar_low, zone_low), zone_high), 4)
                        return {
                            **base,
                            "triggered": True,
                            "action": "buy",
                            "trigger_type": "pullback_buy",
                            "trigger_time": bar_time,
                            "trigger_price": trigger_price,
                            "quantity": quantity,
                            "reason": zone.get("reason", "盘中回踩计划买入区间"),
                            "confidence": "medium",
                            "intraday_source": "1m",
                            "is_reliable": True,
                        }

                if zone["type"] == "breakout_buy" and bar_high >= safe_float(zone.get("price_low"), float("inf")):
                    trigger_price = safe_float(zone.get("price_low"), bar_high)
                    return {
                        **base,
                        "triggered": True,
                        "action": "buy",
                        "trigger_type": "breakout_buy",
                        "trigger_time": bar_time,
                        "trigger_price": round(trigger_price, 4),
                        "quantity": quantity,
                        "reason": zone.get("reason", "盘中突破计划买入区间"),
                        "confidence": "medium",
                        "intraday_source": "1m",
                        "is_reliable": True,
                    }

    # Nothing triggered
    return {
        **base,
        "triggered": False,
        "action": "none",
        "is_reliable": True,
        "reason": "全天未触发计划买入/卖出区间。",
    }
